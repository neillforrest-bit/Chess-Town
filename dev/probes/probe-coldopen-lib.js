const co = require('/tmp/mvout/lib/coldopen.js');
const g = require('/tmp/mvout/lib/game.js');
let pass = 0, fail = 0;
const ok = (c, n) => { if (c) pass++; else { fail++; console.log('FAIL:', n); } };
const spec = co.tonightSpectrum('ROOM1', 0);
ok(co.SPECTRA.includes(spec), 'spectrum from the pool');
ok(co.tonightSpectrum('ROOM1', 0).k === spec.k, 'spectrum stable per room+night');
const tp = co.tropePicks('ROOM1', spec, 20, []);
ok(tp.length === 3 && tp.every(n => g.TROPE_NAMES.includes(n)), 'exactly 3 valid trope picks with no likes');
ok(tp[0] === spec.loTrope, 'low position -> left trope first');
ok(co.tropePicks('ROOM1', spec, 80, [])[0] === spec.hiTrope, 'high position -> right trope first');
const films = co.swipeFilms('ROOM1', 0);
ok(films.length === 3 && films.every(id => g.BY_ID[id] && g.BY_ID[id].r >= 7.2), 'three high-rated swipe posters');
const likedTags = co.tasteTags(spec, 20, 'trophy', films.slice(0, 2));
ok(likedTags.includes('Award winner'), 'trophy pick adds Award winner');
ok(spec.loTag ? likedTags.includes(spec.loTag) : true, 'low lean adds left tag');
const st = co.swipeTropes(films.slice(0, 1));
ok(st.every(n => g.TROPE_NAMES.includes(n)), 'swipe tropes valid');
const line = co.orsonRead({ actors: ['Florence Pugh'], spec, pos: 20, trophy: 'trophy', likedIds: films.slice(0, 1) });
ok(line.includes('Florence Pugh') && line.includes(g.BY_ID[films[0]].t), 'read-back names actor and liked film');
const idx = co.actorIndex();
ok(idx.length > 100, `actor index built (${idx.length})`);
ok(co.searchActors(idx, 'pugh').some(a => a.name === 'Florence Pugh'), 'actor search finds Florence Pugh');
ok(co.searchActors(idx, 'x').length === 0, 'short query returns nothing');
const p = spec.slider(0); ok(p.length === 3 && p.every(v => v >= 0 && v <= 100), 'slider contribution in range');
console.log(`PASS ${pass} FAIL ${fail}`);
process.exit(fail ? 1 : 0);
