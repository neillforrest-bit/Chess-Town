import { chromium } from 'playwright';
import fs from 'node:fs';
const [code, t0, t1, inv] = fs.readFileSync('/tmp/pairs-code.txt', 'utf8').trim().split(' ');
const BASE = 'https://movietime-tv.vercel.app';
const browser = await chromium.launch();
const jem = await (await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage();
await jem.goto(BASE + '/duo#room=' + code);
await jem.evaluate(([c, tok, i]) => localStorage.setItem('movietime-duo:' + c, JSON.stringify({ token: tok, invite: i })), [code, t0, inv]);
await jem.reload();
await jem.waitForFunction(() => /FINAL POINTS|TONIGHT/.test(document.body.innerText), null, { timeout: 25000 });
await jem.waitForTimeout(2500);
await jem.evaluate(() => { const m = document.querySelector('main'); m.scrollTop = 0; });
await jem.screenshot({ path: 'shots/h19-pairs-done-top.png' });
await jem.evaluate(() => { const m = document.querySelector('main'); m.scrollTop = m.scrollHeight; });
await jem.waitForTimeout(2500);
await jem.screenshot({ path: 'shots/h20-pairs-done-film.png' });
const tv = await (await browser.newContext({ viewport: { width: 1920, height: 1080 } })).newPage();
await tv.goto(BASE + '/tv/duo/' + code);
await tv.waitForTimeout(3500);
await tv.screenshot({ path: 'shots/h21-tv-pairs-done.png' });
console.log('phone shows film:', await jem.evaluate(() => /WHERE TO WATCH|No GB streaming/.test(document.body.innerText)), '| tv text has points:', await tv.evaluate(() => /FINAL POINTS|TONIGHT/.test(document.body.innerText)));
await browser.close();
const env = Object.fromEntries(fs.readFileSync('.env.local', 'utf8').split('\n').filter((l) => l.includes('=')).map((l) => { const i = l.indexOf('='); return [l.slice(0, i), l.slice(i + 1).replace(/^"|"$/g, '')]; }));
await fetch(env.NEXT_PUBLIC_SUPABASE_URL.replace(/"/g, '') + '/rest/v1/find_rooms?code=eq.' + code, { method: 'DELETE', headers: { apikey: env.SUPABASE_SERVICE_ROLE_KEY, authorization: 'Bearer ' + env.SUPABASE_SERVICE_ROLE_KEY } }).then((x) => console.log('cleanup', x.status));